"""pricing — credits per feature call on the public API.

One credit is US$0.01 (84 paise), drawn from the same Fliar API wallet as the Radar API and Prism News.
The table is generated by tools/price_features.py from measured call costs (index compute time and model
tokens) at a 3x margin, rounded up to a credit tier; pricing_table.json holds the numbers and how each was
derived. A call that fails or finds nothing is charged zero.
"""
from __future__ import annotations

import json
import os

_HERE = os.path.dirname(os.path.abspath(__file__))

# Not on the public API: operator status and job plumbing, client relays, background article runs,
# and editorial rotation planning.
BLOCKED = {"system.status", "system.article_store", "system.vocabulary", "system.job", "system.request",
           "system.request_status", "system.jobs", "system.retry_job", "client.surface", "client.call",
           "drive.run", "compose.rotation"}
FREE = {"system.features", "system.freshness"}   # discovery costs nothing
FALLBACK = {"news": 3, "research": 8, "analysis": 3, "compose": 12, "system": 1, "drive": 5}


def _table():
    try:
        return json.load(open(os.path.join(_HERE, "pricing_table.json")))["features"]
    except (OSError, ValueError, KeyError):
        return {}


TABLE = _table()


def credits(feature: str) -> int:
    if feature in FREE:
        return 0
    if feature in TABLE:
        return int(TABLE[feature])
    return FALLBACK.get(feature.split(".")[0], 5)


def catalog() -> dict:
    from collections import defaultdict
    groups = defaultdict(dict)
    for f in sorted(set(TABLE) | FREE):
        groups[f.split(".")[0]][f] = credits(f)
    return {"credit": {"usd": 0.01, "inr": 0.84}, "charged": "per successful call; failed or empty answers cost 0",
            "features": dict(groups)}
